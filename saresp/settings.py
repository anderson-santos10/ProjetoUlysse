def _postgres_from_database_url():
    """Usa DATABASE_URL (Railway) sem dependência extra. Ignora URLs não-Postgres."""
    database_url = _env_stripped("DATABASE_URL")
    if not database_url:
        return None
    parsed = urlparse(database_url)
    scheme = (parsed.scheme or "").split("+", 1)[0].lower()
    if scheme not in {"postgres", "postgresql"}:
        return None
    name = unquote((parsed.path or "").lstrip("/"))
    if not name or not parsed.hostname:
        return None
    config = {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": name,
        "USER": unquote(parsed.username or ""),
        "PASSWORD": unquote(parsed.password or ""),
        "HOST": parsed.hostname,
        "PORT": str(parsed.port or "5432"),
    }
    sslmode = (parse_qs(parsed.query).get("sslmode") or [""])[0].strip()
    if sslmode:
        config["OPTIONS"] = {"sslmode": sslmode}
    return config


def _postgres_from_pg_vars():
    host = _env_stripped("PGHOST")
    name = _env_stripped("PGDATABASE")
    if not host or not name:
        return None
    return {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": name,
        "USER": _env_stripped("PGUSER"),
        "PASSWORD": os.environ.get("PGPASSWORD", ""),
        "HOST": host,
        "PORT": _env_stripped("PGPORT") or "5432",
    }


